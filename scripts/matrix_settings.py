"""Build the sandboxed settings page from the playback page's shared editor markup."""
import re


def collect(folder):
    source = (folder / "index.html").read_text(encoding="utf-8")
    match = re.search(r"<!-- culture-editor:start -->(.*?)<!-- culture-editor:end -->", source, re.S)
    if not match:
        raise ValueError("matrix-echo/index.html: missing shared culture editor markers")
    template = (folder / "settings.template.html").read_text(encoding="utf-8")
    if template.count("<!-- MATRIX_CULTURE_EDITOR -->") != 1:
        raise ValueError("matrix-echo/settings.template.html: expected one editor placeholder")
    return ("<!-- Generated by scripts/sync_matrix_settings.py; edit settings.template.html and index.html. -->\n"
            + template.replace("<!-- MATRIX_CULTURE_EDITOR -->", match.group(1).strip())).encode("utf-8")
