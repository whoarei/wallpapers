"""Collect matrix-echo poems into an offline script; no runtime directory fetches."""
import json
import re
from pathlib import Path


def field(value, name, maximum, optional=False):
    if (not isinstance(value, str) or (not optional and not value.strip())
            or len(value) > maximum or any(ord(c) < 32 or 127 <= ord(c) <= 159 for c in value)):
        raise ValueError(f"{name}: expected {'optional ' if optional else ''}single-line text, max {maximum} characters")
    return value.strip()


def identity(title, author):
    value = 2166136261
    for char in title + "\n" + author:
        value = ((value ^ ord(char)) * 16777619) & 0xffffffff
    return f"poem-{value:08x}"


def collect(folder):
    poems, ids, filenames = [], set(), {}
    files = sorted((folder / "content" / "poems").glob("*.json"))
    if not files or len(files) > 500:
        raise ValueError("matrix-echo/content/poems: expected 1–500 JSON files")
    for source in files:
        try:
            if source.is_symlink() or source.stat().st_size > 2 * 1024 * 1024:
                raise ValueError("expected a regular JSON file below 2 MiB")
            value = json.loads(source.read_text(encoding="utf-8-sig"))
            if not isinstance(value, dict):
                raise ValueError("expected one poem object per file")
            title = field(value.get("title"), "title", 80)
            author = field(value.get("author"), "author", 40)
            dynasty = field(value.get("dynasty", ""), "dynasty", 20, True)
            poem_id = value.get("id", identity(title, author))
            if not isinstance(poem_id, str) or not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,63}", poem_id):
                raise ValueError("id: expected 1–64 lowercase letters, digits or hyphens")
            if poem_id in ids:
                raise ValueError(f"duplicate poem id: {poem_id}")
            verses = value.get("verses")
            if not isinstance(verses, list) or not 1 <= len(verses) <= 128:
                raise ValueError("verses: expected 1–128 complete verses")
            verses = [field(v, f"verses[{i}]", 120) for i, v in enumerate(verses)]
            if "enabled" in value and type(value["enabled"]) is not bool:
                raise ValueError("enabled: expected boolean")
            poems.append(dict(id=poem_id, title=title, author=author, dynasty=dynasty,
                              verses=verses, enabled=value.get("enabled", True)))
            ids.add(poem_id)
            filenames[poem_id] = source.name
        except (ValueError, UnicodeError) as error:
            raise ValueError(f"{source.relative_to(folder)}: {error}") from error
    # Escape script delimiters too, so exports can also be embedded safely.
    payload = json.dumps(poems, ensure_ascii=False, indent=2).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return ("// Generated by scripts/sync_matrix_poetry.py; edit content/poems/*.json.\n"
            + "window.MATRIX_POEMS = " + payload + ";\n"
            + "window.MATRIX_POEM_FILES = " + json.dumps(filenames, ensure_ascii=True, sort_keys=True) + ";\n").encode("utf-8")
